import fs from 'node:fs';
import path from 'node:path';

const projectRoot = path.resolve(import.meta.dirname, '..');
const blueprintPath = path.join(
  projectRoot,
  'docs',
  'Health_V5_System_Blueprint_v1.3.3_APPROVED_20_Sheets_FINAL.txt',
);
const outputPath = path.join(projectRoot, 'src', 'SchemaRegistry.gs');
const blueprint = fs.readFileSync(blueprintPath, 'utf8');

const sheetPattern = /^ก\.(\d{2}) ([A-Za-z][A-Za-z0-9]*)\nPurpose: ([^\n]+?) • Canonical field count: (\d+)\nField\nType\nReq\nDefault\nAllowed \/ Validation\nKey \/ Relation\nSensitivity\nVisible Roles \/ Scope\n([\s\S]*?)(?=\n\nก\.\d{2} |\n\nภาคผนวก ข)/gm;
const schemas = [];
let match;

while ((match = sheetPattern.exec(blueprint)) !== null) {
  const [, order, name, purpose, declaredCount, fieldBlock] = match;
  const cells = fieldBlock.trim().split('\n');
  const fieldCount = Number(declaredCount);

  if (cells.length !== fieldCount * 8) {
    throw new Error(
      `${name}: expected ${fieldCount * 8} field cells, found ${cells.length}`,
    );
  }

  const fields = [];
  for (let index = 0; index < cells.length; index += 8) {
    const [
      fieldName,
      type,
      required,
      defaultValue,
      validation,
      relation,
      sensitivity,
      visibleRoles,
    ] = cells.slice(index, index + 8);

    fields.push({
      name: fieldName,
      type,
      required: required === 'Y',
      defaultValue: defaultValue === '—' ? null : defaultValue,
      validation,
      relation: relation === '—' ? null : relation,
      sensitivity,
      visibleRoles,
      allowedValues: parseAllowedValues(validation),
    });
  }

  schemas.push({
    order: Number(order),
    name,
    purpose: purpose.trim(),
    fieldCount,
    fields,
  });
}

if (schemas.length !== 20) {
  throw new Error(`Expected 20 canonical sheets, found ${schemas.length}`);
}

const registry = JSON.stringify(schemas, null, 2);
const generated = `// Generated from Blueprint v1.3.3 by tools/generate-schema-registry.mjs.\n` +
  `// Do not edit this file by hand; update the approved Blueprint and regenerate.\n` +
  `var HEALTH_V5_SCHEMA_VERSION = '1.3.3';\n` +
  `var HEALTH_V5_SCHEMA = ${registry};\n`;

fs.writeFileSync(outputPath, generated, 'utf8');
console.log(`Generated ${path.relative(projectRoot, outputPath)} with ${schemas.length} sheets.`);

function parseAllowedValues(validation) {
  if (!validation.includes('|')) return [];

  const values = validation.split('|').map((value) => value.trim());
  const tokenPattern = /^[A-Z][A-Z0-9_]*$/;
  return values.length >= 2 && values.every((value) => tokenPattern.test(value))
    ? values
    : [];
}
